create extension if not exists "pgcrypto";

-- ------------------------------------------------------------------ TABEL 1
-- users : data akun pelanggan/karyawan/pemilik (dipakai fitur Register)
create table if not exists public.users (
    id          uuid primary key default gen_random_uuid(),
    nama        text        not null,
    email       text        not null unique,
    password    text        not null,                 -- demo: teks biasa, produksi: hash
    telepon     text,
    role        text        not null default 'pelanggan'
                            check (role in ('pelanggan', 'karyawan', 'pemilik')),
    created_at  timestamptz not null default now()
);

-- ------------------------------------------------------------------ TABEL 2
-- layanan : katalog layanan percetakan (topik CRUD ke-1)
create table if not exists public.layanan (
    id          bigint generated by default as identity primary key,
    nama        text        not null,
    kategori    text        not null default 'Umum',
    harga_mulai integer     not null default 0 check (harga_mulai >= 0),
    satuan      text        not null default 'pcs',
    deskripsi   text,
    estimasi    text,
    bahan       text[]      not null default '{}',
    finishing   text[]      not null default '{}',
    aktif       boolean     not null default true,
    created_at  timestamptz not null default now()
);

-- ------------------------------------------------------------------ TABEL 3
-- pesanan : transaksi pelanggan terhadap sebuah layanan (topik CRUD ke-2)
create table if not exists public.pesanan (
    id           bigint generated by default as identity primary key,
    nomor        text        not null unique,
    user_id      uuid        references public.users (id) on delete cascade,
    layanan_id   bigint      references public.layanan (id) on delete set null,
    ukuran       text,
    jumlah       integer     not null default 1 check (jumlah > 0),
    bahan        text,
    finishing    text,
    catatan      text,
    desain_nama  text,
    desain_ukuran text,
    total        integer     not null default 0 check (total >= 0),
    status       text        not null default 'BARU'
                             check (status in ('BARU', 'DESAIN', 'DIPROSES', 'PRODUKSI', 'SELESAI', 'DIBATALKAN')),
    tanggal      date        not null default current_date,
    created_at   timestamptz not null default now()
);

create index if not exists idx_pesanan_user on public.pesanan (user_id);
create index if not exists idx_pesanan_status on public.pesanan (status);
create index if not exists idx_layanan_kategori on public.layanan (kategori);

-- --------------------------------------------- nomor pesanan otomatis #ORD
create sequence if not exists public.pesanan_nomor_seq start with 124;

create or replace function public.set_nomor_pesanan()
returns trigger
language plpgsql
as $$
begin
    if new.nomor is null or new.nomor = '' then
        new.nomor := '#ORD' || lpad(nextval('public.pesanan_nomor_seq')::text, 5, '0');
    end if;
    return new;
end;
$$;

drop trigger if exists trg_set_nomor_pesanan on public.pesanan;
create trigger trg_set_nomor_pesanan
    before insert on public.pesanan
    for each row execute function public.set_nomor_pesanan();

-- ----------------------------------------------------- hak akses REST (anon)
grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on public.users, public.layanan, public.pesanan
    to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- ------------------------------------------------------------------------ RLS
-- CATATAN: policy di bawah adalah mode demo/praktikum (anon boleh semua) supaya
-- fitur CRUD bisa dicoba lewat Retrofit tanpa login Supabase Auth. Untuk
-- produksi ganti `using (true)` dengan `using (auth.uid() = id)`.
alter table public.users   enable row level security;
alter table public.layanan enable row level security;
alter table public.pesanan enable row level security;

drop policy if exists "users_demo_all" on public.users;
create policy "users_demo_all" on public.users
    for all to anon, authenticated using (true) with check (true);

drop policy if exists "layanan_demo_all" on public.layanan;
create policy "layanan_demo_all" on public.layanan
    for all to anon, authenticated using (true) with check (true);

drop policy if exists "pesanan_demo_all" on public.pesanan;
create policy "pesanan_demo_all" on public.pesanan
    for all to anon, authenticated using (true) with check (true);

